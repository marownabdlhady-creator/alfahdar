export type SubServiceFaq = {
  question: string;
  answer: string;
};

/** Everything a sub-service needs before it can carry its own page at
    /services/[slug]/[subSlug]. Fill this block on a sub-service and the
    page generates itself — route, metadata, JSON-LD and internal links
    all read from here, so no other file changes. */
export type SubServicePage = {
  /** The last path segment. Latin, lowercase, hyphenated. */
  subSlug: string;
  /** The keyword-carrying opener under the h1. */
  longDescription: string;
  /** "ما نقدمه" — what the service actually covers. */
  whatWeOffer: string[];
  /** "لماذا الفهدار" — three or four reasons, one line each. */
  whyUs: string[];
  /** Rendered as an accordion and as FAQPage structured data. */
  faqs: SubServiceFaq[];
  keywords: string[];
  seoTitle: string;
  seoDescription: string;
};

type SubServiceBase = {
  name: string;
  description: string;
  /** Its own photo, in /public/services/<category>/<subSlug>.jpg. The
      category photo stands in wherever this is missing, so a category
      can gain its images one at a time. */
  image?: string;
};

/* A sub-service either has the whole page block or none of it — the
   union is what stops a half-filled one from compiling. */
export type SubService = SubServiceBase | (SubServiceBase & SubServicePage);

/** A sub-service that has its own page. */
export type DetailedSubService = Extract<SubService, SubServicePage>;

/** Narrows to the sub-services that have their own page. */
export function hasOwnPage(sub: SubService): sub is DetailedSubService {
  return "subSlug" in sub;
}

export type Service = {
  /** Stable slug; also the photo filename in /public/services. */
  slug: string;
  /** Detail-page route. */
  href: string;
  /** The category name, as it appears in navigation and breadcrumbs. */
  title: string;
  /** Keyword-rich page heading for the detail page's single h1. */
  heading: string;
  /** One line on what the category covers (home cards). */
  summary: string;
  /** One or two sentences (services index). */
  description: string;
  /** The long, keyword-carrying opener on the detail page. */
  intro: string;
  /** Short examples, rendered as a single muted line on the home cards. */
  examples: string[];
  /** The full offering: name + a professional line for each. */
  subServices: SubService[];
  /** Detail-page section and CTA copy that needs correct Arabic grammar. */
  whyHeading: string;
  ctaHeading: string;
  ctaLead: string;
  /* --- SEO ------------------------------------------------------- */
  seoTitle: string;
  seoDescription: string;
  keywords: string[];
  /** schema.org Service.serviceType. */
  serviceType: string;
  image: string;
  alt: string;
};

